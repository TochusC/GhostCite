def setup_plotting():
    """Set plot style for academic publication"""
    os.makedirs('figs', exist_ok=True)
    
    # Use a cleaner base style
    plt.style.use('seaborn-v0_8-whitegrid')
    
    plt.rcParams.update({
        'figure.figsize': (10, 6),
        'axes.grid': False,
        'axes.spines.top': False,
        'axes.spines.right': False,
        'font.family': 'serif',
        'font.serif': ['Times New Roman', 'Times', 'DejaVu Serif'],
        'figure.dpi': 300,
        'savefig.dpi': 300,
        'figure.constrained_layout.use': True,
    })
    print("Setup complete.")


def load_combined_stats(csv_path='survey_combined_statistics.csv'):
    """Load combined statistics from CSV and convert to dict format"""
    df = pd.read_csv(csv_path)
    print(f"Loaded {len(df)} rows from {csv_path}")
    
    # Convert to dict format similar to notebook's combined_stats
    combined_stats = {}
    for question in df['question'].unique():
        q_data = df[df['question'] == question]
        counts = dict(zip(q_data['option'], q_data['count']))
        cn_n = q_data['cn_total'].iloc[0] if len(q_data) > 0 else 0
        en_n = q_data['en_total'].iloc[0] if len(q_data) > 0 else 0
        combined_stats[question] = {
            'counts': counts,
            'cn_n': cn_n,
            'en_n': en_n,
        }
    
    print(f"Loaded {len(combined_stats)} questions")
    return combined_stats


