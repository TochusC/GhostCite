def setup_usenix_style():
    """Setup USENIX Security conference style for figures"""
    plt.rcParams.update({
        'font.family': 'serif',
        'font.serif': ['Times New Roman', 'Times', 'DejaVu Serif'],
        'font.size': 8,
        'axes.titlesize': 9,
        'axes.labelsize': 8,
        'xtick.labelsize': 7,
        'ytick.labelsize': 7,
        'legend.fontsize': 7,
        'figure.dpi': 300,
        'savefig.dpi': 300,
        'axes.linewidth': 0.5,
        'axes.spines.top': False,
        'axes.spines.right': False,
        'figure.constrained_layout.use': True,
    })


# Academic color palette (muted, professional)
USENIX_COLORS = ['#4878A8', '#E57D3A', '#5AA469', '#C75D5D', '#8E7CC3', '#D4A847', '#7FAFC9', '#9E9E9E']


def plot_pie_usenix(data, title, filename, figsize=(2.5, 2.5)):
    """Create a single pie chart in USENIX style"""
    setup_usenix_style()
    
    fig, ax = plt.subplots(figsize=figsize)
    
    # Filter out zero values
    filtered_data = {k: v for k, v in data.items() if v > 0}
    
    colors = USENIX_COLORS[:len(filtered_data)]
    
    # Create pie chart
    wedges, texts, autotexts = ax.pie(
        filtered_data.values(), 
        autopct=lambda pct: f'{pct:.0f}%' if pct >= 5 else '',
        colors=colors,
        textprops={'fontsize': 7, 'color': 'white', 'fontweight': 'bold'},
        pctdistance=0.65,
        startangle=90,
        wedgeprops={'linewidth': 0.5, 'edgecolor': 'white'}
    )
    
    # Add legend outside
    ax.legend(
        wedges, filtered_data.keys(), 
        loc='center left', 
        bbox_to_anchor=(1.0, 0.5),
        fontsize=6,
        frameon=False,
        handlelength=1,
        handleheight=1,
    )
    
    ax.set_title(title, fontsize=9, fontweight='bold', pad=8)
    
    plt.savefig(f'figs/{filename}', dpi=300, bbox_inches='tight', pad_inches=0.05)
    plt.close()
    print(f"Saved: figs/{filename}")


def plot_demographics(combined_stats):
    """Generate 4 separate demographic pie charts in USENIX style"""
    
    # (a) Academic Position
    data = combined_stats.get('position', {}).get('counts', {})
    label_map = {
        'Undergraduate student': 'Undergrad', 
        "Master's Student": "Master's", 
        'PhD Student': 'PhD', 
        'Postdoc': 'Postdoc', 
        'Researcher': 'Researcher',
        'Faculty (Professor/Lecturer)': 'Faculty', 
        'Other': 'Other'
    }
    order = ['Undergraduate student', "Master's Student", 'PhD Student', 'Postdoc', 
             'Researcher', 'Faculty (Professor/Lecturer)', 'Other']
    ordered_data = {}
    for pos in order:
        if pos in data:
            ordered_data[label_map.get(pos, pos)] = data[pos]
    for k in data:
        short_k = label_map.get(k, k[:12])
        if short_k not in ordered_data:
            ordered_data[short_k] = data[k]
    
    plot_pie_usenix(ordered_data, 'Academic Position (N=92)', 'demo_position.pdf')
    
    # (b) Research Area
    data = combined_stats.get('research_area', {}).get('counts', {})
    short_map = {
        'AI & Machine Learning': 'AI/ML',
        'AI Security': 'AI Security',
        'Network Security': 'Network Sec.',
        'System Security': 'System Sec.',
        'Software Engineering': 'Software Eng.',
        'Cryptography': 'Cryptography',
    }
    short_data = {}
    for k, v in data.items():
        short_k = short_map.get(k, k[:15])
        short_data[short_k] = v
    
    plot_pie_usenix(short_data, 'Research Area (N=92)', 'demo_research_area.pdf')
    
    # (c) Papers Published
    data = combined_stats.get('papers_published', {}).get('counts', {})
    order = ['0', '1-5', '6-10', '11-20', '20+']
    ordered_data = {k: data.get(k, 0) for k in order if data.get(k, 0) > 0}
    
    plot_pie_usenix(ordered_data, 'Papers Published (N=92)', 'demo_papers.pdf')
    
    # (d) Reviewer Status
    data = combined_stats.get('is_reviewer', {}).get('counts', {})
    
    plot_pie_usenix(data, 'Served as Reviewer (N=92)', 'demo_reviewer.pdf')
    
    print("All 4 demographic pie charts saved.")


